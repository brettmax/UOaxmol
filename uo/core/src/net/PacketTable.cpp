PacketTable::PacketTable(ClientVersion v) : _version(v)
{
    for (int i = 0; i < 255; ++i)
        _lengths[i] = kBaseLengths[i];
    _lengths[0xFF] = -1;

    using namespace uo::cv;
    auto& t = _lengths;

    if (v >= CV_500A)
    {
        t[0x0B] = 0x07;
        t[0x16] = -1;
        t[0x31] = -1;
    }
    else
    {
        t[0x0B] = 0x10A;
        t[0x16] = 0x01;
        t[0x31] = 0x01;
    }

    t[0xE1] = v >= CV_5090 ? -1 : 0x09;

    if (v >= CV_6013)
    {
        t[0xE3] = -1;
        t[0xE6] = 0x05;
        t[0xE7] = 0x0C;
        t[0xE8] = 0x0D;
        t[0xE9] = 0x4B;
        t[0xEA] = 0x03;
    }
    else
    {
        t[0xE3] = 0x4D;
        t[0xE6] = t[0xE7] = t[0xE8] = t[0xE9] = t[0xEA] = -1;
    }

    if (v >= CV_6017)
    {
        t[0x08] = 0x0F;
        t[0x25] = 0x15;
    }
    else
    {
        t[0x08] = 0x0E;
        t[0x25] = 0x14;
    }

    if (v >= CV_6060)
    {
        t[0xEE] = 0x2000;
        t[0xEF] = 0x2000;
        t[0xF1] = 0x09;
    }
    else
    {
        t[0xEE] = -1;
        t[0xEF] = 0x15;
        t[0xF1] = -1;
    }

    t[0xB9] = v >= CV_60142 ? 0x05 : 0x03;

    if (v >= CV_7000)
    {
        t[0xEE] = 0x0A;
        t[0xEF] = 0x15;
    }
    else
    {
        t[0xEE] = -1;
        t[0xEF] = 0x15;
    }

    if (v >= CV_7090)
    {
        t[0x24] = 0x09;
        t[0x99] = 0x1E;
        t[0xBA] = 0x0A;
        t[0xF3] = 0x1A;
        t[0xF1] = 0x09;
        t[0xF2] = 0x19;
    }
    else
    {
        t[0x24] = 0x07;
        t[0x99] = 0x1A;
        t[0xBA] = 0x06;
        t[0xF3] = 0x18;
        t[0xF1] = -1;
        t[0xF2] = -1;
    }

    t[0x00] = v >= CV_70180 ? 0x6A : 0x68;

    if (v >= CV_706400)
    {
        t[0xFA] = 0x01;
        t[0xFB] = 0x02;
    }

    if (v >= CV_7010400)
    {
        t[0xD5] = 0x09;
        t[0xFD] = 2;
    }
}

